def add(a, b):
    return a + b
print("The sum of 5 and 3 is:", add(5, 3))
def subtract(c, d):
    return c - d
print("The difference of 5 and 3 is:", subtract(5, 3))
def multiply(e, f):
    return e * f
print("The product of 11 and 8 is:", multiply(11, 8))

def divide(g, h):
    return g / h
print("The quotient of 6 and 3 is:", divide(6, 3))

